# TTA
def predict_with_tta(img, n_aug=5):
    preds = [model.predict(np.expand_dims(img, axis=0), verbose=0)[0][0]]
    for _ in range(n_aug):
        aug = img.copy()
        if np.random.random() > 0.5: aug = np.fliplr(aug)
        if np.random.random() > 0.5: aug = aug * np.random.uniform(0.7, 1.3)
        if np.random.random() > 0.5: aug = np.flipud(aug)
        preds.append(model.predict(np.expand_dims(aug, axis=0), verbose=0)[0][0])
    return np.mean(preds)

test_images = []
for p in test_df['filename']:
    img = tf.keras.utils.load_img(p, target_size=(IMG_SIZE, IMG_SIZE))
    test_images.append(tf.keras.utils.img_to_array(img) / 255.0)

tta_preds = [1 if predict_with_tta(img) > 0.5 else 0 for img in test_images]
tta_acc = accuracy_score(test_df['label'], tta_preds)
print(f"✅ TTA Test Accuracy: {tta_acc*100:.2f}%")

print("\n📋 Classification Report (TTA):")
print(classification_report(test_df['label'], tta_preds, target_names=["Benign", "Malignant"]))
print("\n📊 Confusion Matrix (TTA):")
print(confusion_matrix(test_df['label'], tta_preds))

