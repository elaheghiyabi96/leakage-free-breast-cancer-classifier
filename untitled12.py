import os
import numpy as np
import pandas as pd
import tensorflow as tf

tf.keras.mixed_precision.set_global_policy('mixed_float16')

from sklearn.utils.class_weight import compute_class_weight
from tensorflow.keras.applications import DenseNet201
from tensorflow.keras.layers import GlobalAveragePooling2D, Dense, Dropout, BatchNormalization
from tensorflow.keras.models import Sequential
from tensorflow.keras.optimizers import Adam
from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau, ModelCheckpoint
from tensorflow.keras.preprocessing.image import ImageDataGenerator

# Mount Drive
from google.colab import drive
drive.mount('/content/drive')

# بارگذاری تقسیم‌بندی
SPLITS_PATH = "/content/drive/MyDrive/breakhis_ib_outputs/splits_patient_level.csv"
splits_df = pd.read_csv(SPLITS_PATH)

train_df = splits_df[splits_df['split'] == 'train'].reset_index(drop=True)
val_df   = splits_df[splits_df['split'] == 'val'].reset_index(drop=True)

print(f"📊 Train: {len(train_df)}, Val: {len(val_df)}")

# Class Weights
class_weights = compute_class_weight(
    class_weight='balanced',
    classes=np.unique(train_df['label']),
    y=train_df['label']
)
class_weight_dict = dict(enumerate(class_weights))

# Data Generators
IMG_SIZE = 224
BATCH_SIZE = 32

train_datagen = ImageDataGenerator(
    rescale=1./255, rotation_range=45, width_shift_range=0.25,
    height_shift_range=0.25, shear_range=0.2, zoom_range=0.25,
    horizontal_flip=True, vertical_flip=True,
    brightness_range=[0.6, 1.4], channel_shift_range=15, fill_mode='reflect'
)
val_datagen = ImageDataGenerator(rescale=1./255)

train_generator = train_datagen.flow_from_dataframe(
    train_df, x_col="filename", y_col="label",
    target_size=(IMG_SIZE, IMG_SIZE), batch_size=BATCH_SIZE,
    class_mode="raw", shuffle=True
)
val_generator = val_datagen.flow_from_dataframe(
    val_df, x_col="filename", y_col="label",
    target_size=(IMG_SIZE, IMG_SIZE), batch_size=BATCH_SIZE,
    class_mode="raw", shuffle=False
)

steps_per_epoch = len(train_df) // BATCH_SIZE
validation_steps = len(val_df) // BATCH_SIZE

# Model
base_model = DenseNet201(weights='imagenet', include_top=False, input_shape=(IMG_SIZE, IMG_SIZE, 3))
base_model.trainable = False

model = Sequential([
    base_model,
    GlobalAveragePooling2D(),
    BatchNormalization(),
    Dense(512, activation='relu'),
    Dropout(0.5),
    Dense(256, activation='relu'),
    Dropout(0.3),
    Dense(1, activation='sigmoid', dtype='float32')
])

# Callbacks
DRIVE_MODEL_DIR = "/content/drive/MyDrive/breakhis_models"
os.makedirs(DRIVE_MODEL_DIR, exist_ok=True)

callbacks = [
    EarlyStopping(patience=8, restore_best_weights=True, verbose=1),
    ReduceLROnPlateau(factor=0.3, patience=4, min_lr=1e-7, verbose=1),
    ModelCheckpoint(
        os.path.join(DRIVE_MODEL_DIR, 'phase1_frozen_best.keras'),
        save_best_only=True, verbose=1
    )
]

# Train Phase 1
print("\n🚀 PHASE 1: Frozen")
model.compile(optimizer=Adam(1e-3), loss='binary_crossentropy', metrics=['accuracy'])
model.fit(
    train_generator, steps_per_epoch=steps_per_epoch, epochs=30,
    validation_data=val_generator, validation_steps=validation_steps,
    class_weight=class_weight_dict, callbacks=callbacks, verbose=1
)

# ذخیره مدل فاز ۱
phase1_path = os.path.join(DRIVE_MODEL_DIR, 'phase1_frozen_final.keras')
model.save(phase1_path)
print(f"\n💾 Phase 1 model saved: {phase1_path}")
print("✅ PART 1 DONE! Now you can close Colab.")

