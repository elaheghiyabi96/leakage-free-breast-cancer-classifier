import os
import re
import zipfile
import pandas as pd
from sklearn.model_selection import train_test_split

# =========================
# 1️⃣ مسیرها
# =========================
ZIP_PATH = "/content/drive/MyDrive/dataset_cancer_v1.zip"
EXTRACT_PATH = "/content/drive/MyDrive/dataset_cancer_v1_extracted"

if not os.path.exists(ZIP_PATH):
    raise FileNotFoundError(f"❌ Zip not found: {ZIP_PATH}")

# =========================
# 2️⃣ استخراج دیتاست در Drive
# =========================
if not os.path.exists(EXTRACT_PATH):
    print("📂 Extracting dataset to Drive...")
    os.makedirs(EXTRACT_PATH, exist_ok=True)
    with zipfile.ZipFile(ZIP_PATH, 'r') as zip_ref:
        zip_ref.extractall(EXTRACT_PATH)
    print("✅ Extraction completed!")
else:
    print("✅ Dataset already extracted")

# =========================
# 3️⃣ پیدا کردن مسیر classificacao_binaria
# =========================
print("\n🔍 Searching for classificacao_binaria...")
BASE_DIR = None
for root, dirs, files in os.walk(EXTRACT_PATH):
    if os.path.basename(root) == 'classificacao_binaria':
        BASE_DIR = root
        break

if BASE_DIR is None:
    raise FileNotFoundError("❌ classificacao_binaria not found!")

print(f"✅ BASE_DIR = {BASE_DIR}")

# =========================
# 4️⃣ Regex
# =========================
FNAME_REGEX = re.compile(
    r"SOB[_-](?P<bm>[BM])[_-](?P<code>A|F|PT|TA|DC|LC|MC|PC)-(?P<pnum>\d+)-(?P<pid>[A-Za-z0-9]+)-(?P<mag>40|100|200|400)[Xx]?",
    re.I
)

SUBTYPE_CODE2NAME = {
    'A': 'adenosis', 'F': 'fibroadenoma', 'PT': 'phyllodes_tumor', 'TA': 'tubular_adenoma',
    'DC': 'ductal_carcinoma', 'LC': 'lobular_carcinoma', 'MC': 'mucinous_carcinoma', 'PC': 'papillary_carcinoma'
}

# =========================
# 5️⃣ جمع‌آوری تصاویر
# =========================
records = []
for mag in ["40X", "100X", "200X", "400X"]:
    for cls in ["benign", "malignant"]:
        folder = os.path.join(BASE_DIR, mag, cls)
        if not os.path.exists(folder):
            print(f"⚠️ Not found: {folder}")
            continue
        for img_name in os.listdir(folder):
            if not img_name.lower().endswith(('.png', '.jpg', '.jpeg')):
                continue
            m = FNAME_REGEX.search(img_name)
            if not m:
                continue
            code = m.group('code').upper()
            patient_id = f"{code}-{m.group('pid')}"
            records.append({
                'filename': os.path.join(folder, img_name),
                'label': 0 if cls == 'benign' else 1,
                'subtype': SUBTYPE_CODE2NAME.get(code),
                'magnification': mag,
                'patient_id': patient_id
            })

df = pd.DataFrame(records)

if len(df) == 0:
    raise ValueError("❌ No images found!")

print(f"\n📊 Total images: {len(df)}")
print(f"📊 Unique patients: {df['patient_id'].nunique()}")

# =========================
# 6️⃣ تقسیم Patient-Level
# =========================
patient_labels = df.groupby('patient_id')['label'].agg(lambda x: x.mode()[0])
print(f"\n📊 Patient label distribution:\n{patient_labels.value_counts()}")

patients = patient_labels.index.tolist()

train_val_patients, test_patients = train_test_split(
    patients, test_size=0.15, stratify=patient_labels, random_state=42
)
train_patients, val_patients = train_test_split(
    train_val_patients, test_size=0.176,
    stratify=patient_labels[train_val_patients], random_state=42
)

print(f"\n📊 Patient-level split:")
print(f"  Train: {len(train_patients)} patients")
print(f"  Val:   {len(val_patients)} patients")
print(f"  Test:  {len(test_patients)} patients")

# =========================
# 7️⃣ ساخت DataFrames + بررسی نشت
# =========================
train_df = df[df['patient_id'].isin(train_patients)].copy()
val_df   = df[df['patient_id'].isin(val_patients)].copy()
test_df  = df[df['patient_id'].isin(test_patients)].copy()

train_df['split'] = 'train'
val_df['split']   = 'val'
test_df['split']  = 'test'

splits_df = pd.concat([train_df, val_df, test_df], ignore_index=True)

train_set, val_set, test_set = set(train_patients), set(val_patients), set(test_patients)
print(f"\n🔍 Leakage check:")
print(f"  Train ∩ Test: {len(train_set & test_set)}")
print(f"  Train ∩ Val:  {len(train_set & val_set)}")
print(f"  Val ∩ Test:   {len(val_set & test_set)}")

assert len(train_set & test_set) == 0, "Leakage detected!"
assert len(train_set & val_set) == 0, "Leakage detected!"
assert len(val_set & test_set) == 0, "Leakage detected!"
print("  ✅ No leakage! Perfect split!")

# =========================
# 8️⃣ آمار نهایی
# =========================
print(f"\n📊 Image counts per split:")
for split in ['train', 'val', 'test']:
    subset = splits_df[splits_df['split'] == split]
    n_benign = len(subset[subset['label'] == 0])
    n_malignant = len(subset[subset['label'] == 1])
    print(f"  {split}: {len(subset)} images (Benign={n_benign}, Malignant={n_malignant})")

