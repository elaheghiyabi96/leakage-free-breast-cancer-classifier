# ============================================
# DENSENET201 + PATIENT-LEVEL SPLIT (No Leakage)
# ============================================

import os
import numpy as np
import pandas as pd
import tensorflow as tf
from sklearn.utils.class_weight import compute_class_weight
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score
from tensorflow.keras.applications import DenseNet201
from tensorflow.keras.layers import GlobalAveragePooling2D, Dense, Dropout, BatchNormalization
from tensorflow.keras.models import Sequential
from tensorflow.keras.optimizers import Adam
from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau, ModelCheckpoint
from tensorflow.keras.preprocessing.image import ImageDataGenerator
import shutil

# =========================
# 1️⃣ بارگذاری تقسیم‌بندی
# =========================
SPLITS_PATH = "/content/drive/MyDrive/breakhis_ib_outputs/splits_patient_level.csv"
splits_df = pd.read_csv(SPLITS_PATH)

train_df = splits_df[splits_df['split'] == 'train'].reset_index(drop=True)
val_df   = splits_df[splits_df['split'] == 'val'].reset_index(drop=True)
test_df  = splits_df[splits_df['split'] == 'test'].reset_index(drop=True)

print(f"📊 Train: {len(train_df)}, Val: {len(val_df)}, Test: {len(test_df)}")

# =========================
# 2️⃣ Class Weights
# =========================
class_weights = compute_class_weight(
    class_weight='balanced',
    classes=np.unique(train_df['label']),
    y=train_df['label']
)
class_weight_dict = dict(enumerate(class_weights))
print(f"📊 Class Weights: {class_weight_dict}")

# =========================
# 3️⃣ Data Generators
# =========================
IMG_SIZE = 224
BATCH_SIZE = 32

train_datagen = ImageDataGenerator(
    rescale=1./255,
    rotation_range=45,
    width_shift_range=0.25,
    height_shift_range=0.25,
    shear_range=0.2,
    zoom_range=0.25,
    horizontal_flip=True,
    vertical_flip=True,
    brightness_range=[0.6, 1.4],
    channel_shift_range=15,
    fill_mode='reflect'
)
val_datagen = ImageDataGenerator(rescale=1./255)

train_generator = train_datagen.flow_from_dataframe(
    train_df, x_col="filename", y_col="label",
    target_size=(IMG_SIZE, IMG_SIZE), batch_size=BATCH_SIZE,
    class_mode="raw", shuffle=True
)
val_generator = val_datagen.flow_from_dataframe(
    val_df, x_col="filename", y_col="label",
    target_size=(IMG_SIZE, IMG_SIZE), batch_size=BATCH_SIZE,
    class_mode="raw", shuffle=False
)
test_generator = val_datagen.flow_from_dataframe(
    test_df, x_col="filename", y_col="label",
    target_size=(IMG_SIZE, IMG_SIZE), batch_size=BATCH_SIZE,
    class_mode="raw", shuffle=False
)

steps_per_epoch = len(train_df) // BATCH_SIZE
validation_steps = len(val_df) // BATCH_SIZE

# =========================
# 4️⃣ Model (DenseNet201)
# =========================
print("\n🧠 Building DenseNet201...")

base_model = DenseNet201(weights='imagenet', include_top=False, input_shape=(IMG_SIZE, IMG_SIZE, 3))
base_model.trainable = False

model = Sequential([
    base_model,
    GlobalAveragePooling2D(),
    BatchNormalization(),
    Dense(512, activation='relu'),
    Dropout(0.5),
    Dense(256, activation='relu'),
    Dropout(0.3),
    Dense(1, activation='sigmoid')
])

model.summary()

# =========================
# 5️⃣ Callbacks
# =========================
callbacks = [
    EarlyStopping(patience=8, restore_best_weights=True, verbose=1),
    ReduceLROnPlateau(factor=0.3, patience=4, min_lr=1e-7, verbose=1),
    ModelCheckpoint('/content/densenet201_patient_level_best.keras', save_best_only=True, verbose=1)
]

# =========================
# 6️⃣ Training (3 Phases)
# =========================
# Phase 1
print("\n🚀 PHASE 1: Frozen")
model.compile(optimizer=Adam(1e-3), loss='binary_crossentropy', metrics=['accuracy'])
model.fit(train_generator, steps_per_epoch=steps_per_epoch, epochs=30,
          validation_data=val_generator, validation_steps=validation_steps,
          class_weight=class_weight_dict, callbacks=callbacks, verbose=1)

# Phase 2
print("\n🔧 PHASE 2: Fine-Tuning")
base_model.trainable = True
for layer in base_model.layers[:-30]:
    layer.trainable = False
model.compile(optimizer=Adam(5e-5), loss='binary_crossentropy', metrics=['accuracy'])
model.fit(train_generator, steps_per_epoch=steps_per_epoch, epochs=25,
          validation_data=val_generator, validation_steps=validation_steps,
          class_weight=class_weight_dict, callbacks=callbacks, verbose=1)

# Phase 3
print("\n🔧 PHASE 3: Final FT")
model.compile(optimizer=Adam(1e-5), loss='binary_crossentropy', metrics=['accuracy'])
model.fit(train_generator, steps_per_epoch=steps_per_epoch, epochs=15,
          validation_data=val_generator, validation_steps=validation_steps,
          class_weight=class_weight_dict, callbacks=callbacks, verbose=1)

# =========================
# 7️⃣ Evaluation
# =========================
print("\n📊 Final Evaluation on Test Set (Patient-Level)")
test_loss, test_acc = model.evaluate(test_generator, verbose=0)
print(f"✅ Original Test Accuracy: {test_acc*100:.2f}%")

# TTA
def predict_with_tta(img, n_aug=5):
    preds = [model.predict(np.expand_dims(img, axis=0), verbose=0)[0][0]]
    for _ in range(n_aug):
        aug = img.copy()
        if np.random.random() > 0.5: aug = np.fliplr(aug)
        if np.random.random() > 0.5: aug = aug * np.random.uniform(0.7, 1.3)
        if np.random.random() > 0.5: aug = np.flipud(aug)
        preds.append(model.predict(np.expand_dims(aug, axis=0), verbose=0)[0][0])
    return np.mean(preds)

test_images = []
for p in test_df['filename']:
    img = tf.keras.utils.load_img(p, target_size=(IMG_SIZE, IMG_SIZE))
    test_images.append(tf.keras.utils.img_to_array(img) / 255.0)

tta_preds = [1 if predict_with_tta(img) > 0.5 else 0 for img in test_images]
tta_acc = accuracy_score(test_df['label'], tta_preds)
print(f"✅ TTA Test Accuracy: {tta_acc*100:.2f}%")

print("\n📋 Classification Report (TTA):")
print(classification_report(test_df['label'], tta_preds, target_names=["Benign", "Malignant"]))
print("\n📊 Confusion Matrix (TTA):")
print(confusion_matrix(test_df['label'], tta_preds))

# ذخیره مدل نهایی
model.save('/content/densenet201_patient_level_final.keras')
shutil.copy('/content/densenet201_patient_level_final.keras',
            '/content/drive/MyDrive/densenet201_patient_level_final.keras')
print("\n💾 Model saved to Drive.")

